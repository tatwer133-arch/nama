function setup(){
 const entries=new Map();
 const localStorage={getItem:k=>entries.get(k)||null,setItem:(k,v)=>entries.set(k,String(v)),removeItem:k=>entries.delete(k)};
 const sessionStorage={getItem:k=>entries.get('s-'+k)||null,setItem:(k,v)=>entries.set('s-'+k,String(v)),removeItem:k=>entries.delete('s-'+k)};
 const window={fetch:async()=>({})};
 const code=readFileSync(new URL('./public/offline-adapter.js',import.meta.url),'utf8')
 .replace("import {initialGame,applyAction,aiAction} from './game-engine.js';",'')
 .replace(/await import\('\.\/app\.js(?:\?v=\d+)?'\);/,'');
 const adapter=new Function('initialGame','applyAction','aiAction','window','localStorage','sessionStorage','crypto','structuredClone','Response',code+'\nreturn {message,gifts,window};');
 return {...adapter(initialGame,applyAction,aiAction,window,localStorage,sessionStorage,crypto.webcrypto,structuredClone,Response),entries};
}

// Inspect markup generated by the actual renderRoom function, isolated without a browser.
function makeRoomMarkup(room,me,config,menu=false){
 const code=readFileSync(new URL('./public/app.js',import.meta.url),'utf8');
 const start=code.indexOf('function renderRoom(){'),end=code.indexOf('function render(){',start);
 assert(start>=0&&end>start);
 const fmt=n=>String(n??0),esc=s=>String(s??'').replace(/[&<>"']/g,x=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[x]));
 const tones={ruby:['أحمر','🔴'],ocean:['أزرق','🔵'],sun:['أصفر','🟡'],jade:['أخضر','🟢']};
 const avatar=u=>`<span class="avatar-icon">${esc(u?.avatar||'🎮')}</span>`;
 const colorButton=(seat,c)=>`<button class="tone-choice" data-seat="${seat}" data-color="${c}"></button>`;
 const canMove=()=>false,btn=()=>'',cap=()=> 'تجربة';
 const messageMarkup=m=>m.kind==='gift'?`<span class="gift-chat-emoji">${m.emoji}</span>`:m.text;
 const state={room,me,config,giftMenuOpen:menu,captureFx:null,selected:null};
 const fn=new Function('state','tones','avatar','fmt','esc','colorButton','canMove','btn','cap','messageMarkup',code.slice(start,end)+'\nreturn renderRoom();');
 return fn(state,tones,avatar,fmt,esc,colorButton,canMove,btn,cap,messageMarkup);
}

test('gifts are low-price and heart/cake explicitly cost gems',()=>{
 const {message}=setup();const gifts=message('/config','GET').gifts;
 assert.equal(gifts.length,8);
 assert.deepEqual(gifts.filter(g=>g.currency==='gems').map(g=>g.id),['heart','cake']);
 assert(gifts.filter(g=>g.currency==='coins').every(g=>g.price<=6));
 assert.equal(gifts.find(g=>g.id==='heart').price,2);
 assert.equal(gifts.find(g=>g.id==='cake').price,4);
});

test('gift send debits only matching currency and emits image-only chat message',()=>{
 const {message,window}=setup();const me=message('/auth/guest','POST',{name:'أحمد'}).user;
 const room=message('/bot','POST',{size:5}).room;
 const socket=window.io(),events=[];
 socket.on('gift:new',g=>events.push({type:'visual',...g}));
 socket.on('chat:new',g=>events.push({type:'chat',...g}));
 let response;
 socket.emit('gift:send',{id:room.id,gift:'heart'},r=>response=r);
 assert.equal(response.ok,true);
 assert.equal(message('/me','GET').user.coins,me.coins);
 assert.equal(message('/me','GET').user.gems,me.gems-2);
 assert.equal(events[0].type,'chat');assert.equal(events[0].kind,'gift');
 assert.equal(events[0].emoji,'💗');assert.equal(events[0].text,undefined);
 assert.equal(events[1].from,0);assert.equal(events[1].to,1);
 socket.emit('gift:send',{id:room.id,gift:'egg'},r=>response=r);
 assert.equal(message('/me','GET').user.coins,me.coins-3);
 assert.equal(message('/me','GET').user.gems,me.gems-2);
 socket.emit('gift:send',{id:room.id,gift:'cake'},r=>response=r);
 assert.equal(message('/me','GET').user.gems,me.gems-6);
});

test('local multiplayer gift hits the opposite player not the sender',()=>{
 const {message,window}=setup();message('/auth/guest','POST',{name:'سلمى'});
 const room=message('/local','POST',{size:7}).room;
 const socket=window.io();let reaction;
 socket.on('gift:new',g=>reaction=g);
 for(const i of [0,1])socket.emit('game:action',{id:room.id,action:{kind:'place',to:i}},r=>assert.equal(r.ok,true));
 socket.emit('gift:send',{id:room.id,gift:'water'},r=>assert.equal(r.ok,true));
 assert.equal(reaction.from,1);assert.equal(reaction.to,0);
});

